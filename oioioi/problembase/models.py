from django.db import models, transaction
from django.utils.translation import gettext_lazy as _

from oioioi.problems.models import Problem


class ProblemFamily(models.Model):
    """One task, possibly uploaded many times as separate :class:`Problem` objects
    (other contests, later years, slightly modified packages)."""

    creation_date = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = _("problem family")
        verbose_name_plural = _("problem families")

    def __str__(self):
        member = self.members.select_related("problem").order_by("-problem_id").first()
        return member.problem.name if member else f"#{self.id}"


class ProblemFamilyMember(models.Model):
    problem = models.OneToOneField(Problem, primary_key=True, related_name="family_member", on_delete=models.CASCADE)
    family = models.ForeignKey(ProblemFamily, related_name="members", on_delete=models.CASCADE)


class ProblemDescription(models.Model):
    """Short, admin-facing summary of a family: statement without the story,
    solution sketch and difficulty. Math goes in ``$...$``."""

    SOURCE_CHOICES = [
        ("manual", _("written by hand")),
        ("package", _("from the package")),
        ("llm", _("generated by a language model")),
    ]

    family = models.OneToOneField(ProblemFamily, related_name="description", on_delete=models.CASCADE, verbose_name=_("problem family"))
    statement = models.TextField(verbose_name=_("statement summary"))
    solution = models.TextField(blank=True, verbose_name=_("solution summary"))
    rating = models.PositiveSmallIntegerField(null=True, blank=True, verbose_name=_("rating"), help_text=_("Codeforces scale, 800-3500."))
    rating_reason = models.CharField(max_length=500, blank=True, verbose_name=_("rating reason"))
    source = models.CharField(max_length=10, choices=SOURCE_CHOICES, default="manual", verbose_name=_("origin"))
    modified = models.DateTimeField(auto_now=True)

    class Meta:
        verbose_name = _("problem description")
        verbose_name_plural = _("problem descriptions")

    def __str__(self):
        return str(self.family)


class ProblemFingerprint(models.Model):
    """Data read from the package files (filetracker), used to find re-uploads."""

    problem = models.OneToOneField(Problem, primary_key=True, related_name="fingerprint", on_delete=models.CASCADE)
    # [{"name": "abc.cpp", "hash": "..."}] for model solutions (kind NORMAL), normalised
    solution_hashes = models.JSONField(default=list)
    statement_text = models.TextField(blank=True)
    errors = models.TextField(blank=True)
    computed = models.DateTimeField(auto_now=True)


class NotSameProblem(models.Model):
    """A pair of problems an admin marked as different, so they are not suggested again."""

    problem_a = models.ForeignKey(Problem, related_name="+", on_delete=models.CASCADE)
    problem_b = models.ForeignKey(Problem, related_name="+", on_delete=models.CASCADE)

    class Meta:
        unique_together = ("problem_a", "problem_b")


def ensure_families():
    """Give every problem a family (singletons for new problems) and drop empty families."""
    missing = Problem.objects.filter(family_member__isnull=True).values_list("id", flat=True)
    missing = list(missing)
    if missing:
        with transaction.atomic():
            families = ProblemFamily.objects.bulk_create([ProblemFamily() for _ in missing])
            ProblemFamilyMember.objects.bulk_create(
                [ProblemFamilyMember(problem_id=problem_id, family=family) for problem_id, family in zip(missing, families, strict=True)]
            )
    ProblemFamily.objects.filter(members__isnull=True).delete()


@transaction.atomic
def merge_families(family_ids):
    """Merge families into one; returns the remaining family. A description is kept
    from the family that has one (the oldest such)."""
    families = list(ProblemFamily.objects.select_for_update().filter(id__in=family_ids).order_by("id"))
    if len(families) < 2:
        return families[0] if families else None
    with_description = [f for f in families if ProblemDescription.objects.filter(family=f).exists()]
    target = with_description[0] if with_description else families[0]
    others = [f for f in families if f != target]
    ProblemFamilyMember.objects.filter(family__in=others).update(family=target)
    ProblemFamily.objects.filter(id__in=[f.id for f in others]).delete()
    return target


@transaction.atomic
def unlink_problem(problem):
    """Move a problem out of its family into a new one of its own."""
    member = ProblemFamilyMember.objects.select_for_update().get(problem=problem)
    old_family_id = member.family_id
    if member.family.members.count() == 1:
        return member.family
    member.family = ProblemFamily.objects.create()
    member.save()
    remaining = ProblemFamilyMember.objects.filter(family_id=old_family_id).values_list("problem_id", flat=True)
    mark_not_same([problem.id], remaining)
    return member.family


def mark_not_same(problem_ids, other_ids):
    pairs = {(min(a, b), max(a, b)) for a in problem_ids for b in other_ids if a != b}
    NotSameProblem.objects.bulk_create([NotSameProblem(problem_a_id=a, problem_b_id=b) for a, b in pairs], ignore_conflicts=True)
