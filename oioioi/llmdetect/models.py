from django.conf import settings
from django.core.validators import MaxValueValidator, MinValueValidator
from django.db import models
from django.utils import timezone
from django.utils.translation import gettext_lazy as _

from oioioi.contests.models import Contest, ProblemInstance, Round, Submission


class LLMDetectConfig(models.Model):
    """Per-contest settings and the state of the last computation."""

    contest = models.OneToOneField(Contest, related_name="llmdetect_config", on_delete=models.CASCADE)
    trusted_rounds = models.ManyToManyField(
        Round,
        blank=True,
        verbose_name=_("supervised rounds"),
        help_text=_("Rounds written under supervision without internet. Their submissions anchor each participant's style."),
    )
    history_contests = models.ManyToManyField(
        Contest,
        blank=True,
        related_name="+",
        verbose_name=_("earlier contests"),
        help_text=_(
            "Submissions of the same participants in these contests are added to their style profiles (they are not analysed again). "
            "Only contests you administer are listed."
        ),
    )
    history_weight = models.FloatField(
        default=0.5,
        validators=[MinValueValidator(0.05), MaxValueValidator(1.0)],
        verbose_name=_("weight of earlier contests"),
        help_text=_("Weight of a submission from an earlier contest in a profile, compared with one from this contest written on the same day (1)."),
    )
    time_from_statement = models.BooleanField(
        default=False,
        verbose_name=_("count time from opening the statement"),
        help_text=_(
            "Only when participants read the statements in SIO2: with paper statements the first opening is late or never, "
            "and participants would look fast. Otherwise time counts from the start of the round."
        ),
    )
    computed_at = models.DateTimeField(null=True, blank=True)
    # The newest submission included in the last computation.
    last_submission_id = models.IntegerField(default=0)
    # Submissions the last computation could not analyse, and the first reason.
    read_errors = models.PositiveIntegerField(default=0)
    last_error = models.TextField(blank=True)
    # Set when something the results depend on changes, e.g. references.
    dirty = models.BooleanField(default=True)

    class Meta:
        verbose_name = _("LLM detection settings")


def get_config(contest):
    config, _created = LLMDetectConfig.objects.get_or_create(contest=contest)
    return config


def mark_dirty(contest):
    LLMDetectConfig.objects.update_or_create(contest=contest, defaults={"dirty": True})


class SubmissionFeatures(models.Model):
    """Features of the code of one submission, computed once."""

    submission = models.OneToOneField(Submission, related_name="llm_features", on_delete=models.CASCADE)
    version = models.IntegerField()
    language = models.CharField(max_length=16)
    pasted = models.BooleanField(default=False)
    # False when the submission was analysed long after it was sent (e.g. an
    # older contest): then it is unknown whether it was pasted.
    paste_known = models.BooleanField(default=True)
    features = models.JSONField()
    fingerprints = models.JSONField()
    line_hashes = models.JSONField()
    code_lines = models.IntegerField()
    # Coding habits, see habits.extract_habits.
    habits = models.JSONField(default=dict)
    computed_at = models.DateTimeField(default=timezone.now)


class LLMReferenceSolution(models.Model):
    """Code written by an LLM for a problem, the anchor of "close to LLM"."""

    KIND_GENERATED = "generated"
    KIND_CONFIRMED = "confirmed"
    KINDS = (
        (KIND_GENERATED, _("generated by the staff")),
        (KIND_CONFIRMED, _("confirmed case")),
    )

    problem_instance = models.ForeignKey(ProblemInstance, related_name="llm_references", on_delete=models.CASCADE, verbose_name=_("problem"))
    kind = models.CharField(max_length=16, choices=KINDS, default=KIND_GENERATED, verbose_name=_("source"))
    model_name = models.CharField(max_length=100, blank=True, verbose_name=_("model"))
    prompt_variant = models.CharField(max_length=100, blank=True, verbose_name=_("prompt"))
    filename = models.CharField(max_length=255, default="solution.cpp")
    source = models.TextField(verbose_name=_("code"))
    # For confirmed cases: the submission the code comes from.
    submission = models.ForeignKey(Submission, null=True, blank=True, on_delete=models.SET_NULL, related_name="+")
    version = models.IntegerField(default=0)
    features = models.JSONField(default=dict)
    fingerprints = models.JSONField(default=list)
    added_at = models.DateTimeField(default=timezone.now)
    added_by = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.SET_NULL, related_name="+")

    class Meta:
        verbose_name = _("LLM reference solution")
        verbose_name_plural = _("LLM reference solutions")
        ordering = ("problem_instance", "id")

    def __str__(self):
        return f"{self.problem_instance} – {self.model_name or self.get_kind_display()} #{self.id}"

    def save(self, *args, **kwargs):
        from oioioi.llmdetect.features import FEATURES_VERSION, analyze_source

        if self.version != FEATURES_VERSION or not self.fingerprints:
            analysis = analyze_source(self.source, self.filename)
            self.features = analysis["features"]
            self.fingerprints = analysis["fingerprints"]
            self.version = FEATURES_VERSION
        super().save(*args, **kwargs)


class LLMStatement(models.Model):
    """The text of a statement sent in the prompts, read from the problem's
    package or statement file once, then checked and edited by the staff.
    """

    SOURCE_PACKAGE = "package"
    SOURCE_FILE = "file"
    SOURCE_EDITED = "edited"

    problem_instance = models.OneToOneField(ProblemInstance, related_name="llm_statement", on_delete=models.CASCADE)
    text = models.TextField()
    source = models.CharField(max_length=16, blank=True)
    # What may be wrong with the text as it was read.
    warnings = models.JSONField(default=list)
    # Saved by the staff after checking it.
    checked = models.BooleanField(default=False)
    updated_at = models.DateTimeField(default=timezone.now)
    updated_by = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.SET_NULL, related_name="+")


class ProblemViewEvent(models.Model):
    """The first time a user opened the statement of a problem."""

    user = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE)
    problem_instance = models.ForeignKey(ProblemInstance, on_delete=models.CASCADE)
    date = models.DateTimeField()

    class Meta:
        unique_together = (("user", "problem_instance"),)


class RiskAssessment(models.Model):
    """Result of the detection for one submission. This is what the staff sees."""

    submission = models.OneToOneField(Submission, related_name="llm_risk", on_delete=models.CASCADE)
    contest = models.ForeignKey(Contest, on_delete=models.CASCADE, related_name="+")
    user = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="+")
    risk = models.FloatField()
    # {signal: {"value": float, "contribution": float, "detail": str}}
    signals = models.JSONField()
    # Facts shown with the submission: profile confidence, nearest
    # reference, the most similar submission of another participant.
    context = models.JSONField(default=dict)
    computed_at = models.DateTimeField(default=timezone.now)

    class Meta:
        indexes = [models.Index(fields=["contest", "user"])]


class ReviewDecision(models.Model):
    """A decision of the staff about a participant, optionally about one submission."""

    VERDICT_CLEAR = "clear"
    VERDICT_TALK = "talk"
    VERDICT_CONFIRMED = "confirmed"
    VERDICTS = (
        (VERDICT_CLEAR, _("No concerns")),
        (VERDICT_TALK, _("To talk with")),
        (VERDICT_CONFIRMED, _("Confirmed")),
    )

    contest = models.ForeignKey(Contest, on_delete=models.CASCADE, related_name="+")
    # Empty once the data of the contest is purged (llmdetect_purge).
    user = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, on_delete=models.CASCADE, related_name="+")
    submission = models.ForeignKey(Submission, null=True, blank=True, on_delete=models.CASCADE, related_name="+", verbose_name=_("submission"))
    verdict = models.CharField(max_length=16, choices=VERDICTS, verbose_name=_("verdict"))
    note = models.TextField(blank=True, verbose_name=_("note"))
    # The risk at the moment of the decision, to calibrate the weights later.
    risk = models.FloatField(null=True, blank=True)
    signals = models.JSONField(default=dict)
    reviewer = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, on_delete=models.SET_NULL, related_name="+")
    date = models.DateTimeField(default=timezone.now)

    class Meta:
        ordering = ("-date", "-id")
